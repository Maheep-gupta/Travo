#!/usr/bin/env node
// Deploy-time generator for apps/web/dist/_headers (docs/DEPLOYMENT.md step 7).
//   node scripts/generate-headers.mjs --project-url https://<ref>.supabase.co
//   node scripts/generate-headers.mjs --wildcard            (any *.supabase.co project)
//   ... [--out <file>]                                      (default apps/web/dist/_headers)
// The template is deploy/cloudflare/_headers. With --project-url, its wildcard
// connect-src sources are replaced by that one project's exact origin, and a
// marker comment records the origin so `npm run check:dist` can re-derive and
// compare the file. --wildcard copies the template unchanged. One of the two is
// required: the wildcard is never a silent default.
// Offline, zero dependencies. Pure functions are exported for
// scripts/generate-headers.test.mjs; the CLI runs only when this file is executed.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TEMPLATE_PATH = join(ROOT, "deploy", "cloudflare", "_headers");

/** The template's connect-src sources that --project-url replaces. */
export const WILDCARD_SOURCES = "https://*.supabase.co wss://*.supabase.co";

const MARKER_PREFIX = "# Generated by scripts/generate-headers.mjs for ";
const MARKER_RE = /^# Generated by scripts\/generate-headers\.mjs for (\S+)\r?$/m;

// Lower-case DNS labels only (URL() has already lower-cased and punycoded the host).
const HOSTNAME_RE = /^(?=.{1,253}$)[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$/;
const IPV4_RE = /^\d{1,3}(?:\.\d{1,3}){3}$/;
// Names that only resolve on a local network (mDNS, RFC 8375, common private zones).
const PRIVATE_SUFFIXES = ["local", "internal", "lan", "home.arpa"];

/**
 * Validates a Supabase project URL and returns its origin, e.g.
 * "https://abcd.supabase.co". Throws on anything that isn't a bare public
 * https origin: no credentials, port, path, query or fragment, no IP literal,
 * no loopback name and no wildcard. Strict because the value is written into
 * an HTTP header.
 */
export function projectOrigin(input) {
  const raw = String(input ?? "");
  // URL() silently deletes tab, CR and LF anywhere in its input, so
  // "https://a.supa\nbase.co" would become a different, valid host.
  if (/[\t\r\n]/.test(raw)) throw new Error("--project-url must not contain tabs or line breaks");
  let url;
  try {
    url = new URL(raw.trim());
  } catch {
    throw new Error("--project-url is not a valid URL");
  }
  if (url.protocol !== "https:") throw new Error("--project-url must use https://");
  if (url.username || url.password) throw new Error("--project-url must not contain credentials");
  if (url.port) throw new Error("--project-url must not have a port");
  if (url.pathname !== "/" || url.search || url.hash) throw new Error("--project-url must be the bare project URL, with no path, query or fragment");
  const host = url.hostname;
  if (host === "localhost" || host.endsWith(".localhost") || IPV4_RE.test(host) || host.startsWith("[")) {
    throw new Error("--project-url must be a public host name, not loopback or an IP address");
  }
  if (!host.includes(".")) throw new Error("--project-url must be a public host name, not a single-label name");
  if (PRIVATE_SUFFIXES.some((s) => host === s || host.endsWith(`.${s}`))) {
    throw new Error("--project-url must be a public host name, not a local or internal one");
  }
  if (!HOSTNAME_RE.test(host)) throw new Error("--project-url has an invalid host name");
  return `https://${host}`;
}

/**
 * The _headers text for one project origin, or the template unchanged when
 * `origin` is null (wildcard). Throws if the template no longer contains the
 * wildcard sources exactly once, so a template edit can't silently disable it.
 */
export function renderHeaders(template, origin) {
  if (origin === null) return template;
  const parts = template.split(WILDCARD_SOURCES);
  if (parts.length !== 2) {
    throw new Error(`template must contain "${WILDCARD_SOURCES}" exactly once (found ${parts.length - 1})`);
  }
  const host = origin.replace(/^https:\/\//, "");
  const eol = template.includes("\r\n") ? "\r\n" : "\n";
  return `${MARKER_PREFIX}${origin}${eol}${parts.join(`https://${host} wss://${host}`)}`;
}

/** The origin a generated file was rendered for, or null for the plain template. */
export function generatedFor(headersText) {
  const m = MARKER_RE.exec(headersText);
  return m ? m[1] : null;
}

/** What `headersText` should be byte for byte, given the template it claims to come from. */
export function expectedHeaders(template, headersText) {
  const origin = generatedFor(headersText);
  return renderHeaders(template, origin === null ? null : projectOrigin(origin));
}

function main(argv) {
  let values;
  try {
    ({ values } = parseArgs({
      args: argv,
      options: { "project-url": { type: "string" }, wildcard: { type: "boolean" }, out: { type: "string" } },
      strict: true,
    }));
  } catch (e) {
    console.error(`generate-headers: ${e.message}`);
    return 2;
  }
  const hasUrl = values["project-url"] !== undefined;
  if (hasUrl === Boolean(values.wildcard)) {
    console.error("generate-headers: pass exactly one of --project-url <https://<ref>.supabase.co> or --wildcard");
    return 2;
  }
  const out = values.out ? resolve(values.out) : join(ROOT, "apps", "web", "dist", "_headers");
  if (!existsSync(dirname(out))) {
    console.error(`generate-headers: ${dirname(out)} does not exist. Run \`npm run build -w @mc/web\` first.`);
    return 1;
  }
  try {
    const origin = hasUrl ? projectOrigin(values["project-url"]) : null;
    writeFileSync(out, renderHeaders(readFileSync(TEMPLATE_PATH, "utf8"), origin));
    console.log(`generate-headers: wrote ${out} (connect-src: ${origin ?? `wildcard ${WILDCARD_SOURCES}`})`);
    if (origin && !origin.endsWith(".supabase.co")) console.log("generate-headers: note: not a *.supabase.co host; confirm it is the project's custom domain.");
    return 0;
  } catch (e) {
    console.error(`generate-headers: ${e.message}`);
    return 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
